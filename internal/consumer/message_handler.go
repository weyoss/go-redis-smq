type Handler func(ctx context.Context, m *publicmessage.Transferable) error

type MessageHandler struct {
	mu             sync.RWMutex
	running        bool
	consumerID     string
	queue          *queue.Params
	groupID        string
	handler        Handler
	options        *consumer.Options
	ctx            context.Context
	cancel         context.CancelFunc
	dequeuer       *DequeueMessage
	consumeMsg     *ConsumeMessage
	autoDequeue    bool
	ephemeralGroup bool
	batchAcker     *BatchAcker
	batchUnacker   *BatchUnacker
	errCh          chan error

	// wg tracks the two goroutines that directly call internalredis.Client()
	// and lack recover(): loop and acquireWorkerLock. Shutdown waits on wg
	// before doing its own cleanup so no goroutine spawned by this handler
	// is calling Redis after internalredis.Close().
	wg sync.WaitGroup

	scheduledPublisher    *ScheduledPublisher
	delayedRequeuer       *DelayedRequeuer
	immediateRequeuer     *ImmediateRequeuer
	reapConsumers         *ReapConsumers
	orphanedLockRecoverer *OrphanedLockRecoverer

	workerLock *lock.Lock
	log        *slog.Logger
}

func NewMessageHandler(consumerID string, queue *queue.Params, groupID string, handler Handler, options *consumer.Options) *MessageHandler {
	return &MessageHandler{
		consumerID:  consumerID,
		queue:       queue,
		groupID:     groupID,
		handler:     handler,
		options:     options,
		autoDequeue: true,
		errCh:       make(chan error, 1),
		log:         logger.New("consumer", "handler", consumerID, queue.Name()),
	}
}

func (mh *MessageHandler) Queue() *queue.Params { return mh.queue }

func (mh *MessageHandler) IsRunning() bool {
	mh.mu.RLock()
	defer mh.mu.RUnlock()
	return mh.running
}

func (mh *MessageHandler) Errors() <-chan error {
	return mh.errCh
}

// GroupID returns the effective consumer group ID. For Pub/Sub queues
// where no group ID was configured at Consume time, this is the
// ephemeral group ID generated by the library ("cid-" + consumerID).
// For point-to-point queues, this is empty.
//
// Safe to call concurrently. The value is stable after Run returns —
// PrepareConsumerGroup runs inside Run's critical section, so the
// value is well-defined for any reader that observes `running == true`.
func (mh *MessageHandler) GroupID() string {
	mh.mu.RLock()
	defer mh.mu.RUnlock()
	return mh.groupID
}

// Run initializes and starts the handler.
//
// Run is transactional: on any failure, rollbackLocked unwinds whatever
// partial state was created (derived context, ephemeral consumer group,
// Redis subscription, batch ackers, worker lock) before returning the
// error. The handler is left in the same state it was in before Run was
// called, and a subsequent Run with corrected parameters can proceed
// cleanly — no residue, no "already running" surprises.
//
// Rollback runs synchronously under mh.mu. This is safe because the
// fallible steps all complete before any goroutine that depends on the
// initialized state is spawned. The wg-tracked goroutines (acquireWorkerLock,
// loop) and the five background workers are spawned only in the tail of
// Run, after every fallible step has succeeded.
func (mh *MessageHandler) Run(ctx context.Context) error {
	mh.mu.Lock()
	defer mh.mu.Unlock()

	if mh.running {
		mh.log.Debug("already running")
		return nil
	}

	mh.log.Info("starting message handler")

	mh.ctx, mh.cancel = context.WithCancel(ctx)

	effectiveGroupID, err := PrepareConsumerGroup(mh.ctx, mh.consumerID, mh.queue, mh.groupID)
	if err != nil {
		mh.log.Error("failed to prepare consumer group", "error", err)
		mh.rollbackLocked()
		return fmt.Errorf("prepare consumer group: %w", err)
	}
	if effectiveGroupID != "" && effectiveGroupID != mh.groupID {
		mh.groupID = effectiveGroupID
		mh.ephemeralGroup = true
		mh.log.Debug("using ephemeral consumer group", "group", effectiveGroupID)
	}

	if err := SubscribeConsumer(mh.ctx, mh.consumerID, mh.queue, mh.groupID); err != nil {
		mh.log.Error("failed to subscribe consumer", "error", err)
		mh.rollbackLocked()
		return fmt.Errorf("subscribe: %w", err)
	}
	mh.log.Debug("subscribed to queue")

	mh.batchAcker = NewBatchAcker(mh.queue, mh.consumerID, mh.options.BatchAcks)
	mh.batchAcker.Run(mh.ctx)
	mh.log.Debug("batch acker started", "enabled", mh.options.BatchAcks.Enabled)

	mh.batchUnacker = NewBatchUnacker(mh.queue, mh.groupID, mh.consumerID, mh.options.BatchUnacks)
	mh.batchUnacker.Run(mh.ctx)
	mh.log.Debug("batch unacker started", "enabled", mh.options.BatchUnacks.Enabled)

	mh.dequeuer = NewDequeueMessage(mh.queue, mh.groupID, mh.consumerID)
	if err := mh.dequeuer.Init(mh.ctx); err != nil {
		mh.log.Error("failed to initialize dequeuer", "error", err)
		mh.rollbackLocked()
		return fmt.Errorf("dequeue init: %w", err)
	}

	mh.consumeMsg = NewConsumeMessage(mh.queue, mh.groupID, mh.consumerID, mh.handler, mh.batchAcker, mh.batchUnacker)

	qKey := keys.Queue{Namespace: mh.queue.NS(), Name: mh.queue.Name()}
	mh.workerLock = lock.New(
		qKey.WorkersLock(),
		mh.consumerID,
		lock.WithTTL(30*time.Second),
		lock.WithAutoRefresh(10*time.Second),
		lock.WithRetry(lock.ExponentialBackoff(time.Second, 0)),
	)

	// Mark running before spawning any worker. Semantically "we are running"
	// is a precondition for the goroutines that depend on that state to
	// exist. Run holds mh.mu throughout, so the workers can't observe this
	// until they acquire the lock — which happens only after Run returns.
	mh.running = true

	// acquireWorkerLock is tracked by wg. It calls workerLock.Acquire /
	// workerLock.Release (Redis) and has no recover(); a nil-client panic
	// from a concurrent internalredis.Close would crash the process.
	// beginShutdown's wg.Wait covers it.
	mh.wg.Add(1)
	go func() {
		defer mh.wg.Done()
		mh.acquireWorkerLock()
	}()

	if mh.autoDequeue {
		mh.wg.Add(1)
		go func() {
			defer mh.wg.Done()
			mh.loop()
		}()
	}

	mh.log.Info("message handler started",
		"queue", mh.queue.String(),
		"group", mh.groupID,
		"ephemeralGroup", mh.ephemeralGroup,
	)

	return nil
}

// rollbackLocked unwinds partial initialization after a failed Run.
//
// The caller MUST hold mh.mu. No goroutines spawned by Run are running yet
// (acquireWorkerLock and loop are spawned only after every fallible step
// succeeds), so this is fully synchronous — no wg.Wait, no waiting on
// workers. Shares the cleanup steps with beginShutdown (same nil-safe,
// idempotent operations, same order), but is simpler because there are no
// concurrent workers to coordinate with.
//
// Idempotent: every step is nil-safe, so calling twice is harmless. In
// practice it's called once per failed Run, but the discipline matches
// beginShutdown.
//
// Ephemeral group: rollback deletes it. A failed Run leaves the handler
// in a state where it never existed from the caller's perspective, so a
// group it created should not survive. Contrast with beginShutdown's
// deleteEphemeralGroup=false path (Stop), which preserves the group for
// a subsequent resume.
func (mh *MessageHandler) rollbackLocked() {
	if mh.cancel != nil {
		mh.cancel()
	}

	if mh.batchAcker != nil {
		mh.batchAcker.Shutdown()
	}
	if mh.batchUnacker != nil {
		mh.batchUnacker.Shutdown()
	}

	if mh.workerLock != nil {
		if err := mh.workerLock.Release(context.Background()); err != nil {
			mh.log.Error("failed to release worker lock after rollback", "error", err)
		}
	}

	// UnsubscribeConsumer is idempotent — succeeds even if the consumer
	// was never registered (unsubscribe-consumer.lua's HDEL/SREM/DEL on
	// missing keys are all no-ops; the LLEN check on a missing
	// ConsumerProcessing list returns 0). Safe to call unconditionally,
	// even when the failure was at PrepareConsumerGroup before
	// SubscribeConsumer ever ran.
	if err := UnsubscribeConsumer(context.Background(), mh.consumerID, mh.queue, mh.groupID); err != nil {
		mh.log.Error("failed to unsubscribe consumer after rollback", "error", err)
	}

	if mh.ephemeralGroup {
		if err := DeleteEphemeralConsumerGroup(context.Background(), mh.consumerID, mh.queue, mh.groupID); err != nil {
			mh.log.Error("failed to delete ephemeral consumer group after rollback", "error", err)
		}
	}

	// Reset every field so a subsequent Run (or a caller inspecting the
	// discarded mh) sees the pre-Run shape, not a partial init.
	mh.batchAcker = nil
	mh.batchUnacker = nil
	mh.workerLock = nil
	mh.dequeuer = nil
	mh.consumeMsg = nil
	mh.cancel = nil
	mh.ctx = nil
	mh.ephemeralGroup = false
	mh.running = false
}

// acquireWorkerLock blocks until the worker lock is acquired, then starts
// the background recovery workers (scheduler, requeuers, reaper, orphaned
// lock recoverer). Called from a wg-tracked goroutine spawned in Run.
//
// Failure classification:
//
// Acquire returns an error in two very different situations:
//
//  1. ctx cancellation. The handler's beginShutdown cancelled mh.ctx while
//     we were waiting on SetNX. The caller (beginShutdown / Shutdown) owns
//     the full teardown — cancelling derived context, stopping batch
//     ackers, releasing the worker lock, unsubscribing, deleting the
//     ephemeral group. We exit silently. A redundant selfShutdown here
//     would double-log and could race the caller's cleanup.
//
//  2. A real Redis failure (SetNX returned an error — connection refused,
//     WRONGTYPE, transport timeout, etc.). This is a permanent, never-
//     self-resolving degradation. Pre-fix, acquireWorkerLock just logged
//     and returned: running stayed true, the dequeue loop and batch acker
//     kept processing messages, but the five background workers listed
//     below were never spawned. Every failed message accumulated in
//     Requeued / Delayed / Scheduled forever (no requeuer, no scheduler),
//     and dead peers' in-flight messages were never recovered (no reaper).
//     Silent, permanent, invisible from outside.
//
//     Post-fix: signal the failure via errCh (for readers of
//     MessageHandler.Errors) and self-shutdown. The runner's 5s reconcile
//     tick or an onQueueActive state change will spawn a fresh handler on
//     the next cycle, with a fresh chance to acquire the lock.
func (mh *MessageHandler) acquireWorkerLock() {
	mh.log.Debug("attempting to acquire worker lock")
	if err := mh.workerLock.Acquire(mh.ctx); err != nil {
		if mh.ctx.Err() != nil {
			mh.log.Debug("worker lock acquisition cancelled by shutdown")
			return
		}

		mh.log.Error("worker lock acquisition failed — shutting down handler",
			"error", err)

		// errCh is buffered(1); a non-blocking send is safe even when no
		// reader is attached (see Errors). Signals to any future reader
		// (e.g. a runner-side reconciler) that this handler degraded.
		select {
		case mh.errCh <- fmt.Errorf("acquire worker lock: %w", err):
		default:
		}

		// selfShutdown acquires mh.mu internally. This goroutine does NOT
		// hold mh.mu at this point — Run released it long before spawning
		// this goroutine, and we haven't re-acquired it yet (the mu.Lock
		// below runs only on the success path). Safe to call directly.
		//
		// selfShutdown uses waitForLoop=false; beginShutdown does not wait
		// on mh.wg. That's required here: this goroutine is itself tracked
		// by mh.wg, so waiting would deadlock.
		mh.selfShutdown()
		return
	}

	mh.mu.Lock()
	defer mh.mu.Unlock()

	if !mh.running {
		mh.log.Debug("handler stopped before lock acquired — releasing")
		if err := mh.workerLock.Release(context.Background()); err != nil {
			mh.log.Error("failed to release worker lock after stop", "error", err)
		}
		return
	}

	mh.log.Info("worker lock acquired — starting background workers")

	mh.scheduledPublisher = NewScheduledPublisher(mh.queue, mh.groupID, mh.consumerID)
	mh.scheduledPublisher.Run(mh.ctx)

	mh.delayedRequeuer = NewDelayedRequeuer(mh.queue, mh.groupID, mh.consumerID)
	mh.delayedRequeuer.Run(mh.ctx)

	mh.immediateRequeuer = NewImmediateRequeuer(mh.queue, mh.groupID, mh.consumerID)
	mh.immediateRequeuer.Run(mh.ctx)

	mh.reapConsumers = NewReapConsumers(mh.queue, mh.groupID, mh.consumerID)
	mh.reapConsumers.Run(mh.ctx)

	mh.orphanedLockRecoverer = NewOrphanedLockRecoverer(mh.queue, mh.consumerID)
	mh.orphanedLockRecoverer.Run(mh.ctx)

	mh.log.Debug("all background workers started")
}

// Shutdown stops the handler and removes all trace of it: worker lock
// released, subscription removed, ephemeral consumer group deleted (if
// one was in use).
//
// Use Shutdown for permanent removal — Cancel, consumer-level Shutdown,
// AddHandler replace. A handler that has been Shut down cannot be
// resumed under the same group; a subsequent Run would create a new
// group (or reuse the caller's explicit one, in which case there is
// nothing to delete here and the flag is a no-op).
//
// For a temporary stop that preserves the ephemeral group so a later
// StartHandler can resume under the same identity, use Stop.
func (mh *MessageHandler) Shutdown() {
	mh.beginShutdown(true, true)
}

// Stop stops the handler but preserves the ephemeral consumer group.
//
// Use Stop for queue state transitions (pause, stop, lock). The config
// survives, the effective group ID is preserved in Redis's
// ConsumerGroups set, and a subsequent StartHandler will subscribe
// under the same group — matching the identity the caller has been
// using (via Queues(), via events, via anything that observed the
// pre-pause group ID).
//
// Contrast with Shutdown: if a Pub/Sub queue's ephemeral group were
// deleted on pause, a producer targeting that queue between pause and
// resume would fail at publish-message.lua's CONSUMER_GROUP_NOT_FOUND
// check — a queue that is merely paused is not a queue that no longer
// exists. Paused queues must still accept publishes (delivery is what
// pause blocks, not publishing) and those publishes must land in a
// group that exists. Preserving the group is what makes that possible.
func (mh *MessageHandler) Stop() {
	mh.beginShutdown(true, false)
}

// selfShutdown stops the handler from within one of its own goroutines
// (acquireWorkerLock, loop). Passes waitForLoop=false because the caller
// is a wg-tracked goroutine; waiting on wg from inside wg would deadlock.
//
// Preserves the ephemeral group: the handler may be restarted by the
// runner's reconcile tick or a queue state transition, in which case
// the group must still exist so the restarted handler resumes under
// the same identity.
func (mh *MessageHandler) selfShutdown() {
	mh.beginShutdown(false, false)
}

// beginShutdown performs the shutdown sequence.
//
//	waitForLoop          — wait on mh.wg (the dequeue loop and
//	                       acquireWorkerLock). true for external callers
//	                       (Shutdown, Stop); false for selfShutdown
//	                       called from inside one of those goroutines
//	                       (waiting would deadlock).
//
//	deleteEphemeralGroup — delete the handler's ephemeral group from
//	                       Redis. true for permanent removal (Shutdown);
//	                       false for temporary stop or self-shutdown
//	                       (Stop, selfShutdown) so a later StartHandler
//	                       resumes under the same identity.
func (mh *MessageHandler) beginShutdown(waitForLoop, deleteEphemeralGroup bool) {
	mh.mu.Lock()

	if !mh.running {
		mh.mu.Unlock()
		if waitForLoop {
			mh.wg.Wait()
		}
		mh.waitWorkers()
		mh.log.Debug("shutdown called but not running")
		return
	}

	mh.running = false
	cancel := mh.cancel
	batchAcker := mh.batchAcker
	batchUnacker := mh.batchUnacker
	workerLock := mh.workerLock
	ephemeralGroup := mh.ephemeralGroup
	groupID := mh.groupID
	mh.mu.Unlock()

	mh.log.Info("shutting down message handler",
		"deleteEphemeralGroup", deleteEphemeralGroup)

	if cancel != nil {
		cancel()
	}

	if waitForLoop {
		mh.wg.Wait()
	}

	mh.waitWorkers()

	if batchAcker != nil {
		mh.log.Debug("shutting down batch acker")
		batchAcker.Shutdown()
	}
	if batchUnacker != nil {
		mh.log.Debug("shutting down batch unacker")
		batchUnacker.Shutdown()
	}

	if workerLock != nil {
		mh.log.Debug("releasing worker lock")
		if err := workerLock.Release(context.Background()); err != nil {
			mh.log.Error("failed to release worker lock", "error", err)
		}
	}

	mh.log.Debug("unsubscribing consumer")
	if err := UnsubscribeConsumer(context.Background(), mh.consumerID, mh.queue, groupID); err != nil {
		mh.log.Error("failed to unsubscribe consumer", "error", err)
	}

	// Ephemeral group handling depends on why we are shutting down:
	//   - Permanent removal (Shutdown): delete the group. The handler
	//     is going away for good; nothing will ever resume under this
	//     group.
	//   - Temporary stop (Stop, selfShutdown): keep the group. The
	//     runner will restart the handler (reconcile tick, onQueueActive,
	//     or explicit StartHandler), and it must do so under the same
	//     identity so producers that have been targeting this group
	//     continue to reach a live consumer.
	if ephemeralGroup && deleteEphemeralGroup {
		mh.log.Debug("deleting ephemeral consumer group", "group", groupID)
		if err := DeleteEphemeralConsumerGroup(context.Background(), mh.consumerID, mh.queue, groupID); err != nil {
			mh.log.Error("failed to delete ephemeral consumer group", "error", err)
		}
	} else if ephemeralGroup {
		mh.log.Debug("preserving ephemeral consumer group for resume", "group", groupID)
	}

	mh.log.Info("message handler shut down complete")
}

func (mh *MessageHandler) waitWorkers() {
	mh.mu.RLock()
	sp := mh.scheduledPublisher
	dr := mh.delayedRequeuer
	ir := mh.immediateRequeuer
	rc := mh.reapConsumers
	olr := mh.orphanedLockRecoverer
	mh.mu.RUnlock()

	if sp != nil {
		sp.Wait()
	}
	if dr != nil {
		dr.Wait()
	}
	if ir != nil {
		ir.Wait()
	}
	if rc != nil {
		rc.Wait()
	}
	if olr != nil {
		olr.Wait()
	}
}

func (mh *MessageHandler) loop() {
	mh.log.Debug("starting dequeue loop")
	defer close(mh.errCh)
	defer mh.log.Debug("dequeue loop stopped")

	for {
		select {
		case <-mh.ctx.Done():
			return
		default:
		}

		envelope, err := mh.dequeuer.Dequeue(mh.ctx)
		if err != nil {
			// Queue state errors mean the queue is no longer accepting or
			// delivering messages. Signal the runner (via errCh) and stop
			// this handler — the runner will restart it when the queue
			// becomes active again.
			if errors.Is(err, consumer.ErrQueueStopped) ||
				errors.Is(err, consumer.ErrQueueLocked) ||
				errors.Is(err, consumer.ErrQueueInvalidState) {
				mh.log.Warn("queue state changed — stopping handler", "error", err)
				mh.errCh <- fmt.Errorf("handler stopped: %w", err)
				mh.selfShutdown()
				return
			}

			// Cancellation means shutdown is in progress. The pop, rate-
			// limit check, or checkout observed the cancelled ctx; exit
			// silently.
			if errors.Is(err, context.Canceled) || errors.Is(err, context.DeadlineExceeded) {
				mh.log.Debug("dequeue loop exiting", "reason", err)
				return
			}

			// Any other error is a real Redis/network failure. Log at
			// Error so operators can see it, then retry after a short
			// delay.
			mh.log.Error("dequeue error", "error", err)
			select {
			case <-mh.ctx.Done():
				return
			case <-time.After(time.Second):
			}
			continue
		}
		if envelope == nil {
			select {
			case <-mh.ctx.Done():
				return
			case <-time.After(time.Second):
			}
			continue
		}

		mh.consumeMsg.Consume(mh.ctx, envelope)
	}
}
